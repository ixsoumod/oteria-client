# The hole in the middle, bounded by the pale wave (its tip at the bottom right).
HOLE = [(318, 312), (290, 300), (262, 268), (255, 225), (268, 185), (300, 162), (338, 162),
        (366, 190), (380, 222), (384, 248)]

# The cyan wave: its outer edge, then the hole's edge back (the pale wave covers the rest).
CYAN_OUT = [(384, 248), (389, 214), (381, 162), (345, 124), (290, 110), (234, 121), (191, 155),
            (170, 205), (172, 256), (194, 293), (236, 314), (288, 320), (318, 312)]

# The pale wave, inside the cyan one: thick at the top right, thin at the bottom left.
PALE_OUT = [(384, 248), (380, 195), (355, 155), (312, 135), (268, 142), (232, 170), (214, 215),
            (222, 262), (250, 294), (288, 310), (318, 312)]

# The two foam lines under the waves.
FOAM_LONG_OUT = [(104, 372), (160, 400), (240, 414), (320, 408), (390, 393), (432, 386)]
FOAM_LONG_IN = [(432, 386), (390, 378), (320, 388), (240, 392), (160, 386), (104, 372)]
FOAM_SHORT_OUT = [(254, 444), (300, 442), (345, 435), (378, 428)]
FOAM_SHORT_IN = [(378, 428), (345, 426), (300, 432), (254, 444)]

# Flat colours, the earlier logo's blues.
BIG, CYAN, PALE, FOAM = "#1590cc", "#2bbfe9", "#bfeef8", "#a8e4f4"

shapes = [
    ("wave-big", shape(BIG_OUT, BIG_IN), BIG),
    ("wave-cyan", shape(CYAN_OUT, HOLE), CYAN),
    ("wave-pale", shape(PALE_OUT, HOLE), PALE),
    ("foam-long", shape(FOAM_LONG_OUT, FOAM_LONG_IN), FOAM),
    ("foam-short", shape(FOAM_SHORT_OUT, FOAM_SHORT_IN), FOAM),
]

HEAD = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">'
NOTE = "  <!-- Generated by branding/make_logo.py: edit that, not this. -->"

colour = NL.join(f'  <path id="{i}" fill="{fill}" d="{d}"/>' for i, d, fill in shapes)
(HERE / "oteria-logo.svg").write_text(
    NL.join([HEAD, "  <title>Oteria Client</title>", NOTE, colour, "</svg>", ""]),
    encoding="utf-8",
)

# The brand sources `cargo run -p xtask -- icons` turns into every icon (packaging/icons, the
# window icon, the launcher's mark, the avatars): the logo cropped to a square around its waves
# (they span about x 100-434, y 52-444), on nothing, on a white macOS tile, and on white.
BRAND = HERE.parent / "docs" / "media" / "brand"
CROP = 'viewBox="50 30 420 420"'
waves = NL.join(f'    <path fill="{fill}" d="{d}"/>' for _, d, fill in shapes)
