"""Builds branding/oteria-logo.svg and oteria-logo-outline.svg.

Each shape is traced from the reference logo as two edges (points on a 512 square): its
outer edge from one tip to the other, then its inner edge back. Each edge is a smooth
Catmull-Rom curve through its points; the tips, where the edges meet, stay sharp.
Flat colours, no gradient and no dark rim.

Run: python branding/make_logo.py
"""
import pathlib

HERE = pathlib.Path(__file__).parent
NL = "\n"


def spline(points):
    """Cubic Bezier segments ("C ...") through `points` (Catmull-Rom), from the first point."""
    out = []
    for i in range(len(points) - 1):
        p0 = points[i - 1] if i > 0 else points[i]
        p1, p2 = points[i], points[i + 1]
        p3 = points[i + 2] if i + 2 < len(points) else points[i + 1]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append("C{:.1f} {:.1f} {:.1f} {:.1f} {} {}".format(*c1, *c2, *p2))
    return " ".join(out)


def shape(outer, inner):
    """A closed shape: `outer` from tip to tip, then `inner` back to the first tip."""
    assert outer[-1] == inner[0] and inner[-1] == outer[0], "edges must meet at the tips"
    return f"M{outer[0][0]} {outer[0][1]} {spline(outer)} {spline(inner)} Z"


