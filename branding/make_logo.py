BRAND.joinpath("avatar.svg").write_text(on_tile("#ffffff", 0), encoding="utf-8")
for mark in ("mark.svg", "mark-dark.svg"):
    BRAND.joinpath(mark).write_text(NL.join([
        f'<svg xmlns="http://www.w3.org/2000/svg" {CROP}>', "  <title>Oteria Client</title>", NOTE,
        "  <g>", waves, "  </g>", "</svg>", ""]), encoding="utf-8")

# The outline: the same shapes as white lines, each drawn once. The cyan and pale waves share
# the hole's edge, so the cyan one is outlined by its outer edge only.
