    shape(BIG_OUT, BIG_IN),
    f"M{CYAN_OUT[0][0]} {CYAN_OUT[0][1]} {spline(CYAN_OUT)}",
    shape(PALE_OUT, HOLE),
    shape(FOAM_LONG_OUT, FOAM_LONG_IN),
    shape(FOAM_SHORT_OUT, FOAM_SHORT_IN),
